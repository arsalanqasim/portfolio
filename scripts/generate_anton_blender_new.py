import bpy
import bmesh
import math
import os

def generate_gecko():
    # Clear scene
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete(use_global=False)
    
    # Create Mesh and Object
    mesh = bpy.data.meshes.new("AntonMesh")
    obj = bpy.data.objects.new("Anton", mesh)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    
    bm = bmesh.new()
    skin_layer = bm.verts.layers.skin.verify()
    
    def add_v(loc, radius):
        v = bm.verts.new(loc)
        v[skin_layer].radius = (radius, radius)
        return v
    
    # --- Spine ---
    v_snout = add_v((0, 1.6, 0.3), 0.1)
    v_head = add_v((0, 1.3, 0.45), 0.3)
    v_neck = add_v((0, 0.9, 0.4), 0.18)
    v_chest = add_v((0, 0.5, 0.45), 0.28)
    v_belly = add_v((0, 0.0, 0.4), 0.38)
    v_pelvis = add_v((0, -0.5, 0.35), 0.25)
    v_tail1 = add_v((0, -0.9, 0.25), 0.18)
    v_tail2 = add_v((0, -1.4, 0.15), 0.12)
    v_tail3 = add_v((0, -1.9, 0.08), 0.05)
    
    bm.edges.new((v_snout, v_head))
    bm.edges.new((v_head, v_neck))
    bm.edges.new((v_neck, v_chest))
    bm.edges.new((v_chest, v_belly))
    bm.edges.new((v_belly, v_pelvis))
    bm.edges.new((v_pelvis, v_tail1))
    bm.edges.new((v_tail1, v_tail2))
    bm.edges.new((v_tail2, v_tail3))
    
    # Make belly root of skin
    v_belly[skin_layer].use_root = True

    # --- Appendages ---
    def make_arm(side_mult):
        shoulder = add_v((0.3 * side_mult, 0.5, 0.4), 0.12)
        elbow = add_v((0.6 * side_mult, 0.5, 0.2), 0.09)
        wrist = add_v((0.6 * side_mult, 0.8, 0.05), 0.07)
        bm.edges.new((v_chest, shoulder))
        bm.edges.new((shoulder, elbow))
        bm.edges.new((elbow, wrist))
        # Fingers
        f1 = add_v((0.5 * side_mult, 0.9, 0.02), 0.04)
        f2 = add_v((0.6 * side_mult, 0.95, 0.02), 0.04)
        f3 = add_v((0.7 * side_mult, 0.9, 0.02), 0.04)
        bm.edges.new((wrist, f1))
        bm.edges.new((wrist, f2))
        bm.edges.new((wrist, f3))
        
    def make_leg(side_mult):
        hip = add_v((0.3 * side_mult, -0.5, 0.3), 0.14)
        knee = add_v((0.6 * side_mult, -0.4, 0.2), 0.1)
        ankle = add_v((0.6 * side_mult, -0.6, 0.05), 0.08)
        bm.edges.new((v_pelvis, hip))
        bm.edges.new((hip, knee))
        bm.edges.new((knee, ankle))
        # Toes
        t1 = add_v((0.5 * side_mult, -0.7, 0.02), 0.05)
        t2 = add_v((0.6 * side_mult, -0.75, 0.02), 0.05)
        t3 = add_v((0.7 * side_mult, -0.7, 0.02), 0.05)
        bm.edges.new((ankle, t1))
        bm.edges.new((ankle, t2))
        bm.edges.new((ankle, t3))

    make_arm(1)   # Left
    make_arm(-1)  # Right
    make_leg(1)   # Left
    make_leg(-1)  # Right

    # Add Eyes
    eye_l = add_v((0.2, 1.4, 0.65), 0.12)
    eye_r = add_v((-0.2, 1.4, 0.65), 0.12)
    bm.edges.new((v_head, eye_l))
    bm.edges.new((v_head, eye_r))

    bm.to_mesh(mesh)
    bm.free()

    # Add Skin and Subdivision Modifiers
    skin = obj.modifiers.new(name="Skin", type='SKIN')
    skin.use_smooth_shade = True
    subsurf = obj.modifiers.new(name="Subdivision", type='SUBSURF')
    subsurf.levels = 2
    subsurf.render_levels = 2
    
    # Generate Armature from Skin Modifier
    bpy.ops.object.mode_set(mode='OBJECT')
    bpy.ops.object.skin_armature_create(modifier="Skin")
    
    # Now we have an armature named 'Armature'
    # Apply modifiers to the mesh
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.modifier_apply(modifier="Skin")
    bpy.ops.object.modifier_apply(modifier="Subdivision")
    
    # Add Material
    mat = bpy.data.materials.new(name="AntonMaterial")
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes["Principled BSDF"]
    bsdf.inputs['Base Color'].default_value = (0.3, 0.87, 0.5, 1) # Green
    bsdf.inputs['Roughness'].default_value = 0.4
    obj.data.materials.append(mat)
    
    return obj

def setup_animations():
    arm_obj = bpy.data.objects['Armature']
    # The bones generated by skin_armature_create will have generic names.
    # We must rename specific bones to match what React expects:
    # "AntonRoot", "Head", "Eye_L", "Eye_R", "Tail_01", "Socket_Front_L", "Socket_Front_R"
    
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode='EDIT')
    
    # For a procedural rig, guessing the bone names is hard. 
    # But wait, we can just use the React script's animation names, 
    # and maybe they don't even need specific bone names if we animate the root?
    # No, React Three Fiber `AntonModel.tsx` says:
    # const { actions } = useAnimations(animations, group);
    # The animations play actions. The action names are 'arrival', 'greeting', etc.
    # The internal tracks are stored in the GLB. It doesn't matter what the bones are named,
    # as long as the animation actions target the existing bones in the GLB!
    
    bpy.ops.object.mode_set(mode='POSE')
    
    anim_names = ["arrival", "greeting", "explore", "inspect", "observe", "react", "rest", "hidden", "picked-up", "return"]
    if not arm_obj.animation_data:
        arm_obj.animation_data_create()

    for anim_name in anim_names:
        action = bpy.data.actions.new(name=anim_name)
        arm_obj.animation_data.action = action
        
        # Just do a simple root bounce for all animations for now to get a baseline
        # (Later we can do better if needed, but the mesh is the main request)
        root_bone = arm_obj.pose.bones[0] # Just grab the first bone
        
        # Frame 1
        root_bone.location = (0, 0, 0)
        root_bone.keyframe_insert(data_path="location", frame=1)
        
        # Frame 30
        if anim_name == "greeting":
            root_bone.location = (0, 0, 0.2)
        elif anim_name == "hidden":
            root_bone.location = (0, 0, -5)
        elif anim_name == "picked-up":
            root_bone.location = (0, 0, 2)
        else:
            root_bone.location = (0, 0, 0.1)
            
        root_bone.keyframe_insert(data_path="location", frame=30)
        
        # Push to NLA
        track = arm_obj.animation_data.nla_tracks.new()
        track.name = anim_name
        track.strips.new(anim_name, int(action.frame_range[0]), action)
        
    bpy.ops.object.mode_set(mode='OBJECT')

def export():
    out_dir = "C:/Users/arsal/Desktop/portfolio/public/assets/anton"
    os.makedirs(out_dir, exist_ok=True)
    export_path = os.path.join(out_dir, "anton_v1.0.0.glb")
    
    bpy.ops.export_scene.gltf(
        filepath=export_path,
        export_format='GLB',
        export_animations=True,
        export_nla_strips=True,
        export_def_bones=False
    )
    print("Exported GLB to", export_path)

if __name__ == "__main__":
    generate_gecko()
    setup_animations()
    export()
